"""Build the survey's table of contents on the landing page.

Reads the section headings from the survey source and writes HTML into index.html between
the <!-- toc:start --> and <!-- toc:end --> markers. Each section toggles its subsections.
Sections with a figure in FIGURES also carry a preview, which site.css shows on hover.

    python3 scripts/build_toc.py [path/to/clm_survey_vN]
"""
import html, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SURVEY = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', '..', 'clm_survey_v9'))
PAGE = os.path.join(ROOT, 'index.html')
SECTIONS = ['1_intro', '2_motivations', '3_clms', '4_inference_strategies', '5_few_step', '6_scaling',
            '7_applications_eval', '8_challenges', '9_conclusion']

FIGURES = {
    '1': ('timeline_overview.webp', 2999, 1366, 'Figure 1', 'Advances in continuous language models and in the foundations of continuous generation of images and video.'),
    '3': ('statespace_overview.webp', 2218, 1343, 'Figure 3', 'Continuous representations of language for continuous language models.'),
    '4': ('continuous_inference_overview.webp', 2218, 1343, 'Figure 4', 'Inference strategies for continuous language models.'),
    '5': ('few_step_overview.webp', 2218, 1343, 'Figure 5', 'Few-step generation with continuous language models.'),
    '7': ('applications_overview.webp', 2218, 1343, 'Figure 6', 'Evaluation settings for continuous language models.'),
}
CHEVRON = '<svg viewBox="0 0 20 20" aria-hidden="true"><path d="m5 7.5 5 5 5-5"/></svg>'


def esc(s):
    return html.escape(str(s), quote=True)


def headings():
    """Every numbered heading, as a list of top-level sections with nested children."""
    tree, counts = [], [0, 0, 0]
    pattern = r'^\\(section|subsection|subsubsection)\{((?:[^{}]|\{[^{}]*\})*)\}'
    for name in SECTIONS:
        src = open(os.path.join(SURVEY, 'Sections', name + '.tex'), encoding='utf-8').read()
        for level, title in re.findall(pattern, src, re.M):
            depth = ['section', 'subsection', 'subsubsection'].index(level)
            counts[depth] += 1
            counts[depth + 1:] = [0] * (2 - depth)
            node = dict(num='.'.join(map(str, counts[:depth + 1])), title=title.replace('\\&', '&').replace('--', '–'), kids=[])
            (tree if depth == 0 else tree[-1]['kids'] if depth == 1 else tree[-1]['kids'][-1]['kids']).append(node)
    return tree


def label(node):
    return f'<span class="stoc-num">{node["num"]}</span><span>{esc(node["title"])}</span>'


def subsections(nodes):
    items = ''.join(f'<li><span class="stoc-sub">{label(n)}</span>{subsections(n["kids"]) if n["kids"] else ""}</li>' for n in nodes)
    return f'<ol>{items}</ol>'


def section(sec):
    fig = FIGURES.get(sec['num'])
    preview = ''
    if fig:
        name, width, height, number, caption = fig
        preview = f'<figure class="stoc-preview"><img src="assets/figures/{name}" alt="{esc(number + ": " + caption)}" width="{width}" height="{height}" loading="lazy" decoding="async"></figure>'
    if sec['kids']:
        row = f'<details><summary>{label(sec)}{CHEVRON}</summary>{subsections(sec["kids"])}</details>'
    else:
        row = f'<div class="stoc-row">{label(sec)}</div>'
    return f'<li{" class=stoc-has-figure" if fig else ""}>{row}{preview}</li>'


def main():
    tree = headings()
    items = '\n'.join('          ' + section(s) for s in tree)
    block = ('<!-- toc:start (generated by scripts/build_toc.py; do not edit by hand) -->\n'
             '      <nav class="stoc" aria-labelledby="survey-contents-title">\n'
             f'        <ol>\n{items}\n        </ol>\n'
             '      </nav>\n'
             '      <!-- toc:end -->')
    page = open(PAGE, encoding='utf-8').read()
    start, end = page.find('<!-- toc:start'), page.find('<!-- toc:end -->')
    assert start >= 0 and end > start, 'index.html needs the <!-- toc:start --> and <!-- toc:end --> markers'
    page = page[:start] + block + page[end + len('<!-- toc:end -->'):]
    open(PAGE, 'w', encoding='utf-8').write(page)
    print(f'{len(tree)} sections, {sum(len(s["kids"]) for s in tree)} subsections')


if __name__ == '__main__':
    main()
